import { sql } from "drizzle-orm";
import { check, char, foreignKey, index, jsonb, numeric, pgTable, smallint, text, timestamp, unique, uuid, varchar } from "drizzle-orm/pg-core";
import { merchantEnvironments, merchants } from "./merchants.ts";
import { canonicalOrderStatusEnum, chainVerificationStateEnum, paymentIntentStateEnum } from "./enums.ts";

export const paymentIntents = pgTable("payment_intents", {
  id: uuid("id").defaultRandom().primaryKey(),
  merchantId: uuid("merchant_id").notNull().references(() => merchants.id, { onDelete: "restrict" }),
  environmentId: uuid("environment_id").notNull(),
  externalOrderId: varchar("external_order_id", { length: 128 }).notNull(),
  buyerAddress: char("buyer_address", { length: 42 }).notNull(),
  currency: char("currency", { length: 4 }).default("USDC").notNull(),
  amountBaseUnits: numeric("amount_base_units", { precision: 78, scale: 0, mode: "bigint" }).notNull(),
  fundingDeadline: timestamp("funding_deadline", { withTimezone: true }).notNull(),
  settlementDeadline: timestamp("settlement_deadline", { withTimezone: true }).notNull(),
  applicationState: paymentIntentStateEnum("application_state").default("planned").notNull(),
  canonicalStatus: canonicalOrderStatusEnum("canonical_status").default("none").notNull(),
  canonicalObservedAt: timestamp("canonical_observed_at", { withTimezone: true }),
  reconciliationState: varchar("reconciliation_state", { length: 40 }).default("unobserved").notNull(),
  activatedAt: timestamp("activated_at", { withTimezone: true }),
  fundedAt: timestamp("funded_at", { withTimezone: true }),
  completedAt: timestamp("completed_at", { withTimezone: true }),
  refundedAt: timestamp("refunded_at", { withTimezone: true }),
  cancelledAt: timestamp("cancelled_at", { withTimezone: true }),
  orderId: char("order_id", { length: 66 }).notNull(),
  termsHash: char("terms_hash", { length: 66 }).notNull(),
  checkoutPath: text("checkout_path"),
  metadata: jsonb("metadata").$type<Record<string, unknown>>().default({}).notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
}, (table) => [
  foreignKey({ name: "payment_intents_environment_owner_fk", columns: [table.merchantId, table.environmentId], foreignColumns: [merchantEnvironments.merchantId, merchantEnvironments.id] }).onDelete("restrict"),
  unique("payment_intents_merchant_environment_id_unique").on(table.merchantId, table.environmentId, table.id),
  unique("payment_intents_external_order_unique").on(table.merchantId, table.environmentId, table.externalOrderId),
  unique("payment_intents_environment_order_id_unique").on(table.environmentId, table.orderId),
  index("payment_intents_tenant_created_idx").on(table.merchantId, table.environmentId, table.createdAt),
  index("payment_intents_tenant_state_idx").on(table.merchantId, table.environmentId, table.applicationState),
  index("payment_intents_canonical_observed_idx").on(table.canonicalStatus, table.canonicalObservedAt),
  check("payment_intents_amount_positive", sql`${table.amountBaseUnits} > 0`),
  check("payment_intents_currency_usdc", sql`${table.currency} = 'USDC'`),
  check("payment_intents_deadline_order", sql`${table.settlementDeadline} > ${table.fundingDeadline}`),
  check("payment_intents_external_order_not_blank", sql`length(btrim(${table.externalOrderId})) > 0`),
  check("payment_intents_buyer_normalized", sql`${table.buyerAddress} ~ '^0x[0-9a-f]{40}$' and ${table.buyerAddress} <> '0x0000000000000000000000000000000000000000'`),
  check("payment_intents_order_id_format", sql`${table.orderId} ~ '^0x[0-9a-f]{64}$' and ${table.orderId} <> ('0x' || repeat('0', 64))`),
  check("payment_intents_terms_hash_format", sql`${table.termsHash} ~ '^0x[0-9a-f]{64}$' and ${table.termsHash} <> ('0x' || repeat('0', 64))`),
  check("payment_intents_checkout_path_safe", sql`${table.checkoutPath} is null or (${table.checkoutPath} like '/pay/%' and length(${table.checkoutPath}) <= 256)`),
  check("payment_intents_observation_consistent", sql`(${table.canonicalStatus} = 'none' and ${table.canonicalObservedAt} is null) or (${table.canonicalStatus} <> 'none' and ${table.canonicalObservedAt} is not null)`),
]);

export const paymentIntentRecipients = pgTable("payment_intent_recipients", {
  id: uuid("id").defaultRandom().primaryKey(),
  paymentIntentId: uuid("payment_intent_id").notNull().references(() => paymentIntents.id, { onDelete: "restrict" }),
  recipientAddress: char("recipient_address", { length: 42 }).notNull(),
  shareBps: smallint("share_bps").notNull(),
  position: smallint("position").notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
}, (table) => [
  unique("payment_intent_recipients_position_unique").on(table.paymentIntentId, table.position),
  unique("payment_intent_recipients_address_unique").on(table.paymentIntentId, table.recipientAddress),
  index("payment_intent_recipients_intent_idx").on(table.paymentIntentId),
  check("payment_intent_recipients_share_range", sql`${table.shareBps} between 1 and 10000`),
  check("payment_intent_recipients_position_range", sql`${table.position} between 0 and 7`),
  check("payment_intent_recipients_address_normalized", sql`${table.recipientAddress} ~ '^0x[0-9a-f]{40}$' and ${table.recipientAddress} <> '0x0000000000000000000000000000000000000000'`),
]);

export const chainOrders = pgTable("chain_orders", {
  id: uuid("id").defaultRandom().primaryKey(),
  paymentIntentId: uuid("payment_intent_id").notNull().references(() => paymentIntents.id, { onDelete: "restrict" }),
  chainId: numeric("chain_id", { precision: 78, scale: 0, mode: "bigint" }).notNull(),
  contractAddress: char("contract_address", { length: 42 }).notNull(),
  orderId: char("order_id", { length: 66 }).notNull(),
  termsHash: char("terms_hash", { length: 66 }).notNull(),
  canonicalStatus: canonicalOrderStatusEnum("canonical_status").default("none").notNull(),
  lastVerifiedBlock: numeric("last_verified_block", { precision: 78, scale: 0, mode: "bigint" }),
  lastVerifiedBlockHash: char("last_verified_block_hash", { length: 66 }),
  lastVerifiedPayloadHash: char("last_verified_payload_hash", { length: 66 }),
  verificationState: chainVerificationStateEnum("verification_state").default("unverified").notNull(),
  lastVerifiedAt: timestamp("last_verified_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
}, (table) => [
  unique("chain_orders_payment_intent_unique").on(table.paymentIntentId),
  unique("chain_orders_chain_contract_order_unique").on(table.chainId, table.contractAddress, table.orderId),
  index("chain_orders_verification_state_idx").on(table.verificationState, table.lastVerifiedAt),
  check("chain_orders_chain_id_positive", sql`${table.chainId} > 0`),
  check("chain_orders_contract_normalized", sql`${table.contractAddress} ~ '^0x[0-9a-f]{40}$' and ${table.contractAddress} <> '0x0000000000000000000000000000000000000000'`),
  check("chain_orders_order_id_format", sql`${table.orderId} ~ '^0x[0-9a-f]{64}$' and ${table.orderId} <> ('0x' || repeat('0', 64))`),
  check("chain_orders_terms_hash_format", sql`${table.termsHash} ~ '^0x[0-9a-f]{64}$' and ${table.termsHash} <> ('0x' || repeat('0', 64))`),
  check("chain_orders_verification_consistent", sql`(${table.canonicalStatus} = 'none' and ${table.lastVerifiedAt} is null) or (${table.canonicalStatus} <> 'none' and ${table.lastVerifiedAt} is not null)`),
  check("chain_orders_block_evidence_pair", sql`(${table.lastVerifiedBlock} is null and ${table.lastVerifiedBlockHash} is null) or (${table.lastVerifiedBlock} >= 0 and ${table.lastVerifiedBlockHash} ~ '^0x[0-9a-f]{64}$')`),
  check("chain_orders_payload_hash_format", sql`${table.lastVerifiedPayloadHash} is null or ${table.lastVerifiedPayloadHash} ~ '^0x[0-9a-f]{64}$'`),
]);