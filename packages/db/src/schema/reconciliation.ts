import { sql } from "drizzle-orm";
import { char, check, foreignKey, index, integer, jsonb, numeric, pgEnum, pgTable, timestamp, unique, uuid, varchar } from "drizzle-orm/pg-core";

import { merchantEnvironments, merchants } from "./merchants.ts";
import { paymentIntents } from "./payment-intents.ts";

export const chainObservationStateEnum = pgEnum("chain_observation_state", ["canonical", "orphaned"]);
export const reconciliationIssueStateEnum = pgEnum("reconciliation_issue_state", ["open", "resolved"]);
export const reconciliationIssueSeverityEnum = pgEnum("reconciliation_issue_severity", ["warning", "error"]);

export const chainReconciliationCursors = pgTable("chain_reconciliation_cursors", {
  id: uuid("id").defaultRandom().primaryKey(),
  chainId: numeric("chain_id", { precision: 78, scale: 0, mode: "bigint" }).notNull(),
  contractAddress: char("contract_address", { length: 42 }).notNull(),
  deploymentBlock: numeric("deployment_block", { precision: 78, scale: 0, mode: "bigint" }).notNull(),
  confirmationDepth: integer("confirmation_depth").notNull(),
  nextBlock: numeric("next_block", { precision: 78, scale: 0, mode: "bigint" }).notNull(),
  lastScannedBlock: numeric("last_scanned_block", { precision: 78, scale: 0, mode: "bigint" }),
  lastScannedBlockHash: char("last_scanned_block_hash", { length: 66 }),
  lastSafeBlock: numeric("last_safe_block", { precision: 78, scale: 0, mode: "bigint" }),
  leaseOwner: varchar("lease_owner", { length: 120 }),
  leaseUntil: timestamp("lease_until", { withTimezone: true }),
  consecutiveFailures: integer("consecutive_failures").default(0).notNull(),
  lastErrorCode: varchar("last_error_code", { length: 120 }),
  lastSuccessfulRunAt: timestamp("last_successful_run_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
}, (table) => [
  unique("chain_reconciliation_cursors_chain_contract_unique").on(table.chainId, table.contractAddress),
  index("chain_reconciliation_cursors_claimable_idx").on(table.leaseUntil, table.updatedAt),
  check("chain_reconciliation_cursors_chain_positive", sql`${table.chainId} > 0`),
  check("chain_reconciliation_cursors_contract_normalized", sql`${table.contractAddress} ~ '^0x[0-9a-f]{40}$' and ${table.contractAddress} <> '0x0000000000000000000000000000000000000000'`),
  check("chain_reconciliation_cursors_deployment_nonnegative", sql`${table.deploymentBlock} >= 0`),
  check("chain_reconciliation_cursors_confirmation_range", sql`${table.confirmationDepth} between 1 and 1024`),
  check("chain_reconciliation_cursors_next_valid", sql`${table.nextBlock} >= ${table.deploymentBlock}`),
  check("chain_reconciliation_cursors_scan_pair", sql`(${table.lastScannedBlock} is null and ${table.lastScannedBlockHash} is null) or (${table.lastScannedBlock} >= ${table.deploymentBlock} and ${table.lastScannedBlockHash} ~ '^0x[0-9a-f]{64}$')`),
  check("chain_reconciliation_cursors_safe_nonnegative", sql`${table.lastSafeBlock} is null or ${table.lastSafeBlock} >= 0`),
  check("chain_reconciliation_cursors_lease_pair", sql`(${table.leaseOwner} is null and ${table.leaseUntil} is null) or (${table.leaseOwner} is not null and ${table.leaseUntil} is not null)`),
  check("chain_reconciliation_cursors_failures_nonnegative", sql`${table.consecutiveFailures} >= 0`),
]);

export const chainObservations = pgTable("chain_observations", {
  id: uuid("id").defaultRandom().primaryKey(),
  cursorId: uuid("cursor_id").notNull().references(() => chainReconciliationCursors.id, { onDelete: "restrict" }),
  merchantId: uuid("merchant_id").references(() => merchants.id, { onDelete: "restrict" }),
  environmentId: uuid("environment_id"),
  paymentIntentId: uuid("payment_intent_id").references(() => paymentIntents.id, { onDelete: "restrict" }),
  chainId: numeric("chain_id", { precision: 78, scale: 0, mode: "bigint" }).notNull(),
  contractAddress: char("contract_address", { length: 42 }).notNull(),
  orderId: char("order_id", { length: 66 }).notNull(),
  blockNumber: numeric("block_number", { precision: 78, scale: 0, mode: "bigint" }).notNull(),
  blockHash: char("block_hash", { length: 66 }).notNull(),
  transactionHash: char("transaction_hash", { length: 66 }).notNull(),
  logIndex: integer("log_index").notNull(),
  eventName: varchar("event_name", { length: 40 }).notNull(),
  payload: jsonb("payload_json").$type<Record<string, unknown>>().notNull(),
  payloadHash: char("payload_hash", { length: 64 }).notNull(),
  state: chainObservationStateEnum("state").default("canonical").notNull(),
  observedAt: timestamp("observed_at", { withTimezone: true }).defaultNow().notNull(),
  canonicalAt: timestamp("canonical_at", { withTimezone: true }).notNull(),
  orphanedAt: timestamp("orphaned_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
}, (table) => [
  foreignKey({ name: "chain_observations_environment_owner_fk", columns: [table.merchantId, table.environmentId], foreignColumns: [merchantEnvironments.merchantId, merchantEnvironments.id] }).onDelete("restrict"),
  foreignKey({ name: "chain_observations_intent_owner_fk", columns: [table.merchantId, table.environmentId, table.paymentIntentId], foreignColumns: [paymentIntents.merchantId, paymentIntents.environmentId, paymentIntents.id] }).onDelete("restrict"),
  unique("chain_observations_cursor_transaction_log_unique").on(table.cursorId, table.transactionHash, table.logIndex),
  index("chain_observations_order_block_idx").on(table.chainId, table.contractAddress, table.orderId, table.blockNumber, table.logIndex),
  index("chain_observations_intent_block_idx").on(table.paymentIntentId, table.blockNumber, table.logIndex),
  index("chain_observations_state_block_idx").on(table.state, table.blockNumber),
  check("chain_observations_tenant_consistent", sql`(${table.merchantId} is null and ${table.environmentId} is null and ${table.paymentIntentId} is null) or (${table.merchantId} is not null and ${table.environmentId} is not null and ${table.paymentIntentId} is not null)`),
  check("chain_observations_chain_positive", sql`${table.chainId} > 0`),
  check("chain_observations_contract_normalized", sql`${table.contractAddress} ~ '^0x[0-9a-f]{40}$' and ${table.contractAddress} <> '0x0000000000000000000000000000000000000000'`),
  check("chain_observations_order_id_format", sql`${table.orderId} ~ '^0x[0-9a-f]{64}$' and ${table.orderId} <> ('0x' || repeat('0', 64))`),
  check("chain_observations_block_nonnegative", sql`${table.blockNumber} >= 0`),
  check("chain_observations_block_hash_format", sql`${table.blockHash} ~ '^0x[0-9a-f]{64}$'`),
  check("chain_observations_transaction_hash_format", sql`${table.transactionHash} ~ '^0x[0-9a-f]{64}$'`),
  check("chain_observations_log_index_nonnegative", sql`${table.logIndex} >= 0`),
  check("chain_observations_event_not_blank", sql`length(btrim(${table.eventName})) > 0`),
  check("chain_observations_payload_object", sql`jsonb_typeof(${table.payload}) = 'object'`),
  check("chain_observations_payload_hash_format", sql`${table.payloadHash} ~ '^[0-9a-f]{64}$'`),
  check("chain_observations_state_consistent", sql`(${table.state} = 'canonical' and ${table.orphanedAt} is null) or (${table.state} = 'orphaned' and ${table.orphanedAt} is not null)`),
]);

export const reconciliationIssues = pgTable("reconciliation_issues", {
  id: uuid("id").defaultRandom().primaryKey(),
  cursorId: uuid("cursor_id").notNull().references(() => chainReconciliationCursors.id, { onDelete: "restrict" }),
  merchantId: uuid("merchant_id").references(() => merchants.id, { onDelete: "restrict" }),
  environmentId: uuid("environment_id"),
  paymentIntentId: uuid("payment_intent_id").references(() => paymentIntents.id, { onDelete: "restrict" }),
  orderId: char("order_id", { length: 66 }),
  kind: varchar("kind", { length: 80 }).notNull(),
  severity: reconciliationIssueSeverityEnum("severity").default("error").notNull(),
  state: reconciliationIssueStateEnum("state").default("open").notNull(),
  canonicalKey: char("canonical_key", { length: 64 }).notNull(),
  details: jsonb("details_json").$type<Record<string, unknown>>().default({}).notNull(),
  firstObservedAt: timestamp("first_observed_at", { withTimezone: true }).defaultNow().notNull(),
  lastObservedAt: timestamp("last_observed_at", { withTimezone: true }).defaultNow().notNull(),
  resolvedAt: timestamp("resolved_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
}, (table) => [
  foreignKey({ name: "reconciliation_issues_environment_owner_fk", columns: [table.merchantId, table.environmentId], foreignColumns: [merchantEnvironments.merchantId, merchantEnvironments.id] }).onDelete("restrict"),
  foreignKey({ name: "reconciliation_issues_intent_owner_fk", columns: [table.merchantId, table.environmentId, table.paymentIntentId], foreignColumns: [paymentIntents.merchantId, paymentIntents.environmentId, paymentIntents.id] }).onDelete("restrict"),
  unique("reconciliation_issues_cursor_kind_key_unique").on(table.cursorId, table.kind, table.canonicalKey),
  index("reconciliation_issues_tenant_state_idx").on(table.merchantId, table.environmentId, table.state, table.lastObservedAt),
  index("reconciliation_issues_intent_state_idx").on(table.paymentIntentId, table.state, table.lastObservedAt),
  index("reconciliation_issues_cursor_state_idx").on(table.cursorId, table.state, table.lastObservedAt),
  check("reconciliation_issues_tenant_consistent", sql`(${table.merchantId} is null and ${table.environmentId} is null and ${table.paymentIntentId} is null) or (${table.merchantId} is not null and ${table.environmentId} is not null and ${table.paymentIntentId} is not null)`),
  check("reconciliation_issues_order_id_format", sql`${table.orderId} is null or (${table.orderId} ~ '^0x[0-9a-f]{64}$' and ${table.orderId} <> ('0x' || repeat('0', 64)))`),
  check("reconciliation_issues_kind_not_blank", sql`length(btrim(${table.kind})) > 0`),
  check("reconciliation_issues_key_format", sql`${table.canonicalKey} ~ '^[0-9a-f]{64}$'`),
  check("reconciliation_issues_details_object", sql`jsonb_typeof(${table.details}) = 'object'`),
  check("reconciliation_issues_state_consistent", sql`(${table.state} = 'open' and ${table.resolvedAt} is null) or (${table.state} = 'resolved' and ${table.resolvedAt} is not null)`),
]);
